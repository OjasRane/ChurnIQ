import { test, expect } from '@playwright/test'
import fs from 'node:fs'
import path from 'node:path'

test('real API, navigation, dynamic prediction, upload, finance, AI error, model insights', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Customer Retention Intelligence' })).toBeVisible()
  await expect(page.getByText('2,280', { exact: true }).first()).toBeVisible()
  await page.screenshot({ path: 'test-results/overview-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Predict Churn', exact: true }).click()
  await expect(page.locator('form input,form select')).toHaveCount(12)
  await page.getByLabel('Stability_Index', { exact: true }).fill('20')
  await page.getByRole('button', { name: 'Predict churn risk' }).click()
  await expect(page.getByText('Prediction result', { exact: true })).toBeVisible()
  await expect(page.getByText('Why this prediction?', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Bulk Analysis', exact: true }).click()
  await page.getByLabel('Upload customer CSV').setInputFiles(path.resolve('../data/test (1).csv'))
  await expect(page.getByText('Customer predictions', { exact: true })).toBeVisible()
  await expect(page.getByText('Page 1 of 29')).toBeVisible()
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download competition CSV' }).click()
  const download = await downloadEvent
  const file = await download.path()
  const csv = fs.readFileSync(file!, 'utf8')
  expect(csv.trim().split('\n')).toHaveLength(571)
  expect(csv.split('\n')[0].trim()).toBe('id,prediction')
  await page.getByRole('button', { name: 'Profit Simulator', exact: true }).click()
  await expect(page.getByText('Campaign allocation', { exact: true })).toBeVisible()
  const revenue=page.getByLabel('Monthly customer revenue', { exact: true })
  const contribution = page.locator('.finance-stats .stat').first().locator('strong')
  const originalContribution = await contribution.textContent()
  await revenue.fill('100')
  await expect(contribution).not.toHaveText(originalContribution!)
  await expect(page.getByText('100', { exact: true }).first()).toBeVisible()
  await expect(page.getByText('Discounted contribution / customer', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'AI Analyst', exact: false }).first().click()
  await page.getByRole('button', { name: 'Generate analysis', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Gemini is not configured')
  await page.getByRole('button', { name: 'Model Insights', exact: true }).click()
  await expect(page.getByText('Three models. One honest comparison.')).toBeVisible()
  await expect(page.getByText('0.9922', { exact: true }).first()).toBeVisible()
  await expect(page.getByText('3,624', { exact: true })).toBeVisible()
  expect(errors).toEqual([])
})

