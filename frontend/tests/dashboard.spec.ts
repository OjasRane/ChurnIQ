test('CSV and backend connection errors provide recovery', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Bulk Analysis', exact: true }).click()
  await page.getByLabel('Upload customer CSV').setInputFiles({name:'invalid.csv',mimeType:'text/csv',buffer:Buffer.from('id,bad\n1,2\n')})
  await expect(page.getByRole('alert')).toContainText('Missing required features')
  await page.route('**/api/overview', route => route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:'Backend temporarily unavailable'})}))
  await page.reload()
  await expect(page.getByRole('alert')).toContainText('Backend temporarily unavailable')
  await page.unroute('**/api/overview')
  await page.getByRole('button', {name:'Retry',exact:true}).click()
  await expect(page.getByText('2,280', {exact:true}).first()).toBeVisible()
})
